#!/usr/bin/env python3
"""Vendor the Sovereign SDK `sov-sequencer` crate into modules/sov-sequencer and apply Selendra's patches.

Why: Selendra patches the preferred sequencer (see modules/patches/README.md). Cargo's `[patch]` in the root Cargo.toml
swaps the git crate for this local copy; every other SDK crate still comes from the pinned git rev.

Usage (from selendra/):
    python3 scripts/vendor_sov_sequencer.py            # uses the SDK rev pinned in Cargo.toml
    python3 scripts/vendor_sov_sequencer.py <rev>      # after ./scripts/update_rev.sh <rev>

It fetches the SDK at <rev> (cached under target/sdk-src), copies the crate, rewrites its Cargo.toml so
`workspace = true` entries point at the same git rev, then applies modules/patches/*.patch in order.
If a patch no longer applies after an SDK upgrade, fix it by hand in modules/sov-sequencer and
regenerate the .patch (see modules/patches/README.md).
"""
import re
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SDK_URL = "https://github.com/Sovereign-Labs/sovereign-sdk.git"
CRATE = "crates/full-node/sov-sequencer"
DEST = ROOT / "modules" / "sov-sequencer"
PATCHES = ROOT / "modules" / "patches"


def pinned_rev() -> str:
    m = re.search(r'sovereign-sdk\.git", rev = "([0-9a-f]+)"', (ROOT / "Cargo.toml").read_text())
    if not m:
        sys.exit("could not find the SDK rev in Cargo.toml")
    return m.group(1)


def fetch_sdk(rev: str) -> Path:
    src = ROOT / "target" / "sdk-src" / rev
    if not (src / CRATE).exists():
        src.mkdir(parents=True, exist_ok=True)
        run = lambda *a: subprocess.run(["git", "-C", str(src), *a], check=True)
        run("init", "-q")
        run("remote", "add", "origin", SDK_URL)
        run("fetch", "-q", "--depth", "1", "origin", rev)
        run("checkout", "-q", "FETCH_HEAD")
    return src


def toml_value(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, str):
        return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(v, list):
        return "[" + ", ".join(toml_value(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{ " + ", ".join(f"{k} = {toml_value(x)}" for k, x in v.items()) + " }"
    return str(v)


def resolve_dep(name: str, spec, ws_deps: dict, rev: str) -> dict:
    if isinstance(spec, str):
        return {"version": spec}
    spec = dict(spec)
    if not spec.pop("workspace", False):
        return spec
    ws = ws_deps[name]
    ws = {"version": ws} if isinstance(ws, str) else dict(ws)
    if "path" in ws:  # an SDK crate: take it from the same git rev as everything else
        ws.pop("path")
        ws.pop("version", None)
        ws = {"git": SDK_URL, "rev": rev, **ws}
    features = list(dict.fromkeys(ws.pop("features", []) + spec.pop("features", [])))
    out = {**ws, **spec}
    if features:
        out["features"] = features
    return out


def rewrite_manifest(src_manifest: Path, ws_manifest: Path, rev: str) -> str:
    crate = tomllib.loads(src_manifest.read_text())
    ws = tomllib.loads(ws_manifest.read_text())["workspace"]
    ws_pkg, ws_deps = ws["package"], ws["dependencies"]

    pkg = {k: (ws_pkg[k] if isinstance(v, dict) and v.get("workspace") else v) for k, v in crate["package"].items()}
    lines = [
        "# GENERATED by scripts/vendor_sov_sequencer.py from sovereign-sdk " + rev,
        "# Do not edit by hand: change modules/patches/*.patch and re-run the script.",
        "",
        "[package]",
    ]
    lines += [f"{k} = {toml_value(v)}" for k, v in pkg.items()]
    lines += ["", "[dependencies]"]
    for name, spec in crate["dependencies"].items():
        lines.append(f"{name} = {toml_value(resolve_dep(name, spec, ws_deps, rev))}")
    # dev-dependencies are dropped: the SDK's own test suite is not run from Selendra.
    # The SDK workspace allows unknown cfgs (e.g. `migration-script`, `tokio_unstable`); keep that.
    lines += ["", "[lints.rust]", 'unexpected_cfgs = "allow"']
    if "features" in crate:
        lines += ["", "[features]"]
        lines += [f"{k} = {toml_value(v)}" for k, v in crate["features"].items()]
    return "\n".join(lines) + "\n"


def main():
    rev = sys.argv[1] if len(sys.argv) > 1 else pinned_rev()
    sdk = fetch_sdk(rev)
    if DEST.exists():
        shutil.rmtree(DEST)
    crate_root = str(sdk / CRATE)
    # Skip only the crate's top-level integration tests (they need the SDK's dev-dependencies).
    skip_top_level = lambda d, names: [n for n in names if d == crate_root and n in ("tests", "target")]
    shutil.copytree(sdk / CRATE, DEST, ignore=skip_top_level)
    (DEST / "Cargo.toml").write_text(rewrite_manifest(sdk / CRATE / "Cargo.toml", sdk / "Cargo.toml", rev))
    print(f"vendored {CRATE} @ {rev[:8]} -> {DEST.relative_to(ROOT)}")

    for patch in sorted(PATCHES.glob("*.patch")):
        r = subprocess.run(["patch", "-p1", "--forward", "--no-backup-if-mismatch", "-d", str(DEST), "-i", str(patch)])
        if r.returncode != 0:
            sys.exit(f"patch {patch.name} did not apply cleanly; fix modules/sov-sequencer by hand and regenerate it")
        print(f"applied {patch.name}")


if __name__ == "__main__":
    main()
