#!/usr/bin/env python3
"""Vendor the Sovereign SDK crates Selendra patches into modules/<crate> and apply Selendra's patches.

Why: Selendra patches a few SDK crates (see modules/patches/README.md). Cargo's `[patch]` in the root Cargo.toml
swaps each git crate for its local copy; every other SDK crate still comes from the pinned git rev.

Usage (from selendra/):
    python3 scripts/vendor_sdk_crates.py            # uses the SDK rev pinned in Cargo.toml
    python3 scripts/vendor_sdk_crates.py <rev>      # after ./scripts/update_rev.sh <rev>

It fetches the SDK at <rev> (cached under target/sdk-src), copies each crate in CRATES, rewrites its Cargo.toml so
`workspace = true` entries point at the same git rev, then applies that crate's patches in order.
If a patch no longer applies after an SDK upgrade, fix it by hand in modules/<crate> and
regenerate the .patch (see modules/patches/README.md).
"""
import re
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SDK_URL = "https://github.com/Sovereign-Labs/sovereign-sdk.git"
PATCHES = ROOT / "modules" / "patches"
# crate name -> (path inside the SDK, patches in modules/patches applied in order)
CRATES = {
    "sov-sequencer": ("crates/full-node/sov-sequencer", ["0001-skip-empty-batches-while-idle.patch"]),
    "sov-evm": (
        "crates/module-system/module-implementations/sov-evm",
        ["0002-evm-rpc-block-by-synthetic-hash.patch"],
    ),
    "sov-stf-runner": (
        "crates/full-node/sov-stf-runner",
        ["0003-stf-runner-restart-with-proof-backlog.patch"],
    ),
}


def pinned_rev() -> str:
    m = re.search(r'sovereign-sdk\.git", rev = "([0-9a-f]+)"', (ROOT / "Cargo.toml").read_text())
    if not m:
        sys.exit("could not find the SDK rev in Cargo.toml")
    return m.group(1)


def fetch_sdk(rev: str) -> Path:
    src = ROOT / "target" / "sdk-src" / rev
    if not all((src / path).exists() for path, _ in CRATES.values()):
        if src.exists():
            shutil.rmtree(src)
        src.mkdir(parents=True)
        run = lambda *a: subprocess.run(["git", "-C", str(src), *a], check=True)
        run("init", "-q")
        run("remote", "add", "origin", SDK_URL)
        run("fetch", "-q", "--depth", "1", "origin", rev)
        run("checkout", "-q", "FETCH_HEAD")
    return src


def toml_value(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, str):
        return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(v, list):
        return "[" + ", ".join(toml_value(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{ " + ", ".join(f"{k} = {toml_value(x)}" for k, x in v.items()) + " }"
    return str(v)


def resolve_dep(name: str, spec, ws_deps: dict, rev: str) -> dict:
    if isinstance(spec, str):
        return {"version": spec}
    spec = dict(spec)
    if not spec.pop("workspace", False):
        return spec
    ws = ws_deps[name]
    ws = {"version": ws} if isinstance(ws, str) else dict(ws)
    if "path" in ws:  # an SDK crate: take it from the same git rev as everything else
        ws.pop("path")
        ws.pop("version", None)
        ws = {"git": SDK_URL, "rev": rev, **ws}
    features = list(dict.fromkeys(ws.pop("features", []) + spec.pop("features", [])))
    out = {**ws, **spec}
    if features:
        out["features"] = features
    return out


def keep_feature_entry(entry: str, deps: dict, features: dict) -> bool:
    """Drop feature entries that point at dev-dependencies, which are not vendored."""
    if entry.startswith("dep:"):
        return entry[4:] in deps
    if "/" in entry:
        return entry.split("/", 1)[0].rstrip("?") in deps
    return entry in features or entry in deps


def rewrite_manifest(src_manifest: Path, ws_manifest: Path, rev: str) -> str:
    crate = tomllib.loads(src_manifest.read_text())
    ws = tomllib.loads(ws_manifest.read_text())["workspace"]
    ws_pkg, ws_deps = ws["package"], ws["dependencies"]

    pkg = {k: (ws_pkg[k] if isinstance(v, dict) and v.get("workspace") else v) for k, v in crate["package"].items()}
    lines = [
        "# GENERATED by scripts/vendor_sdk_crates.py from sovereign-sdk " + rev,
        "# Do not edit by hand: change modules/patches/*.patch and re-run the script.",
        "",
        "[package]",
    ]
    lines += [f"{k} = {toml_value(v)}" for k, v in pkg.items()]
    lines += ["", "[dependencies]"]
    deps = crate["dependencies"]
    for name, spec in deps.items():
        lines.append(f"{name} = {toml_value(resolve_dep(name, spec, ws_deps, rev))}")
    # dev-dependencies, tests and benches are dropped: the SDK's own test suite is not run from Selendra.
    # The SDK workspace allows unknown cfgs (e.g. `migration-script`, `tokio_unstable`); keep that.
    lines += ["", "[lints.rust]", 'unexpected_cfgs = "allow"']
    if "features" in crate:
        features = crate["features"]
        lines += ["", "[features]"]
        lines += [
            f"{k} = {toml_value([e for e in v if keep_feature_entry(e, deps, features)])}"
            for k, v in features.items()
        ]
    return "\n".join(lines) + "\n"


def vendor(name: str, path: str, patches: list[str], sdk: Path, rev: str):
    dest = ROOT / "modules" / name
    if dest.exists():
        shutil.rmtree(dest)
    crate_root = str(sdk / path)
    # Skip only the crate's top-level tests and benches (they need the SDK's dev-dependencies).
    skip_top_level = lambda d, names: [n for n in names if d == crate_root and n in ("tests", "benches", "target")]
    shutil.copytree(sdk / path, dest, ignore=skip_top_level)
    (dest / "Cargo.toml").write_text(rewrite_manifest(sdk / path / "Cargo.toml", sdk / "Cargo.toml", rev))
    print(f"vendored {path} @ {rev[:8]} -> {dest.relative_to(ROOT)}")

    for patch in patches:
        r = subprocess.run(["patch", "-p1", "--forward", "--no-backup-if-mismatch", "-d", str(dest), "-i", str(PATCHES / patch)])
        if r.returncode != 0:
            sys.exit(f"patch {patch} did not apply cleanly; fix modules/{name} by hand and regenerate it")
        print(f"applied {patch}")


def main():
    rev = sys.argv[1] if len(sys.argv) > 1 else pinned_rev()
    sdk = fetch_sdk(rev)
    for name, (path, patches) in CRATES.items():
        vendor(name, path, patches, sdk, rev)


if __name__ == "__main__":
    main()
